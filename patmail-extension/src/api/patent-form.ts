export function defaultPatentVisibleColumns(includeProc: boolean): string[] {
  return PATENT_COLUMNS
    .filter(col => col.defaultVisible && (includeProc || !col.isProc))
    .map(col => col.field)
}

export function buildColselString(fields: readonly string[]): string {
  const unique = [...new Set(fields.map(f => f.trim()).filter(Boolean))]
  return unique.length ? `;${unique.join(';')};` : ';case_volume;case_name;'
}

