export function buildPatentExportGroups(includeProcess: boolean): FeeExportGroup[] {
  return groups.slice(0, includeProcess ? groups.length : 5).map(([id, title, columns]) => ({
    id, title, columns: columns.map(([value, text, defaultChecked]) => ({ value, text, defaultChecked }))
  }))
}

export function buildPatentExportParams(
  query: PatentSearchQuery,
  pageAuth: string,
  columns: FeeExportColumn[]
): URLSearchParams {
  return new URLSearchParams({
    Call: 'ICCaseSearchToExcel',
    Element: buildPatentSearchElement(query),
    is_proc: String(Boolean(query.is_proc)),
    select_and: String(Boolean(query.select_and)),
    is_fuzzy_query_app_no: String(Boolean(query.is_fuzzy_query_app_no)),
    is_fuzzy_query_case_volume: String(Boolean(query.is_fuzzy_query_case_volume)),
    is_point_app_no: String(Boolean(query.is_point_app_no)),
    is_remove_symbol: String(Boolean(query.is_remove_symbol)),
    is_fuzzy_query_pct_app_no: String(Boolean(query.is_fuzzy_query_pct_app_no)),
    PageAuth: pageAuth,
    orderby: '',
    colname: '',
    e_coulums: buildExportColumnsXml(columns, true),
    log_pagename: 'IhgAdvExport.aspx'
  })
}
